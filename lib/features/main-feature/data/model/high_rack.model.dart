import '../../domain/entity/high_rack.entity.dart';

class HighRackModel {
  Data? data;
  int? code;
  bool? succeeded;
  String? message;
  String? description;

  HighRackModel({
    required this.data,
    required this.code,
    required this.succeeded,
    required this.message,
    required this.description,
  });

  factory HighRackModel.fromJson(Map<String, dynamic> json) => HighRackModel(
        data: json["Data"] != null ? Data.fromJson(json["Data"]) : null,
        code: json["Code"],
        succeeded: json["Succeeded"],
        message: json["Message"],
        description: json["Description"],
      );

  HighRackEntity toEntity() {
    return HighRackEntity(
      data: data?.toEntity(),
      code: code,
      succeeded: succeeded,
      message: message,
      description: description,
    );
  }
}

